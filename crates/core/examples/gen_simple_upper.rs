//! Writes `src/yaml/simple_upper.rs` from a `UnicodeData.txt` 15.0.0 file.
//!
//! Usage: `gen_simple_upper <UnicodeData.txt> <simple_upper.rs>`.

use std::{env, fmt::Write as _, fs, process::ExitCode};

const HEADER: &str = "// @generated by `just simple-upper` from UnicodeData.txt 15.0.0, the Unicode version of .NET 8: simple uppercase mappings (field 12) without U+0131 and U+017F.\n";

fn main() -> ExitCode {
    match run() {
        Ok(()) => ExitCode::SUCCESS,
        Err(e) => {
            eprintln!("gen_simple_upper: {e}");
            ExitCode::FAILURE
        }
    }
}

fn run() -> Result<(), Box<dyn std::error::Error>> {
    let mut args = env::args().skip(1);
    let (Some(input), Some(output)) = (args.next(), args.next()) else {
        return Err("usage: gen_simple_upper <UnicodeData.txt> <simple_upper.rs>".into());
    };
    let data = fs::read_to_string(&input)?;
    let mut pairs = Vec::new();
    let mut codes = Vec::new();
    for line in data.lines() {
        let fields: Vec<&str> = line.split(';').collect();
        let (Some(code), Some(upper)) = (fields.first(), fields.get(12)) else {
            return Err(format!("{input}: malformed line `{line}`").into());
        };
        let code = u32::from_str_radix(code, 16)?;
        codes.push(code);
        if upper.is_empty() || matches!(code, 0x0131 | 0x017F) {
            continue;
        }
        pairs.push((code, u32::from_str_radix(upper, 16)?));
    }
    if !codes.contains(&0x1E030) || codes.contains(&0x2FFC) || codes.contains(&0x10D50) {
        return Err(format!("{input} is not UnicodeData.txt 15.0.0").into());
    }
    pairs.sort_unstable();
    let mut table = String::from(HEADER);
    writeln!(
        table,
        "pub(super) const SIMPLE_UPPER: [(char, char); {}] = [",
        pairs.len()
    )?;
    for (code, upper) in pairs {
        writeln!(table, "    ('\\u{{{code:04X}}}', '\\u{{{upper:04X}}}'),")?;
    }
    table.push_str("];\n");
    fs::write(output, table)?;
    Ok(())
}
